import { offerFingerprint, scope } from './tradeApprovalState'
import { ProposalVerdict } from './tradeScore/ProposalVerdict'
import { linkedOfferStyle, useLinkedOffer } from './linkedOffer'

function ProposalPlayers({ label, players, roster, week }: {
  label: string; players: TradeOffer['incoming_players']; roster: TradeContextPlayer[]; week?: number
}) {
  return <Stack gap="xs">
    <Text size="xs" fw={700} tt="uppercase" c={label === 'You get' ? 'var(--incoming)' : 'var(--outgoing)'}>{label}</Text>
    {players.map(player => {
      const details = roster.find(candidate => candidate.espn_id === player.espn_id)
      const vorp = week == null ? null : details?.metrics[String(week)]?.vorp_score
      return <PlayerCard key={player.espn_id} variant="row" className="proposal-player"
        player={{ id: player.espn_id, name: details?.name || player.name || `ESPN player ${player.espn_id}`, position: details?.position, team: details?.nfl_team }}
        stats={details && <Text size="sm" fw={700}>{vorp == null ? 'VORP unavailable' : `${vorp.toFixed(1)} VORP`}</Text>}
        badges={details && <ByeBadge byeWeek={details.nfl_bye_week} week={week} />} />
    })}
  </Stack>
}

export function OutgoingTradeProposals({ config, linkedOfferKey, players = [], week }: {
  config: DraftConfig
  linkedOfferKey?: string | null
  players?: TradeContextPlayer[]
  week?: number
}) {
  const linked = useLinkedOffer(linkedOfferKey)
  const query = useOutgoingTradeOffers(config)
  const names = useQuery({
    queryKey: ['trade-team-names', config.league_id],
    queryFn: () => getTeamNames(config.league_id),
    staleTime: 900_000,
  }, queryClient)

  return (
    <section id="approve" aria-label="Outgoing trade proposals">
      <Group justify="space-between" mb="sm">
        <h2>Ready to approve</h2>
        <Button variant="default" size="xs" loading={query.isFetching}
          onClick={() => { void query.refetch(); void names.refetch() }}>
          Refresh proposals
        </Button>
      </Group>
      <Text size="sm" c="dimmed" mb="md">
        Generated by the twice-weekly scan. Nothing is sent until you approve.
      </Text>
      {query.isPending && (
        <SkeletonRegion label="Loading outgoing trade proposals">
          <TextSkeleton lines={5} />
        </SkeletonRegion>
      )}
      {query.isError && (
        <Alert color="red" mb="md">
          Could not load outgoing proposals: {query.error.message}
          {Boolean(query.data?.length) && ' Previously loaded proposals are shown below and may be out of date.'}
        </Alert>
      )}
      {!query.isError && query.data?.length === 0 && (
        <Text c="dimmed">No outgoing proposals awaiting approval.</Text>
      )}
      <div className="proposal-grid">
        {query.data?.map((offer) => (
          <ProposalCard key={`${scope(config)}:${offer.id}:${offerFingerprint(offer)}:${offer.drafted_message}`} offer={offer} config={config} roster={players} week={week} teamNames={names.data} cardRef={linked.refFor(offer.offer_key)} isLinked={linked.isLinked(offer.offer_key)} disabled={query.isError || query.isFetching} />
        ))}
      </div>
      <TradeApprovalStatus key={`${config.league_id}:${config.team_id}:${config.season}:${config.mode}`} config={config} />
    </section>
  )
}

function ProposalCard({ offer, config, teamNames, roster, week, cardRef, isLinked, disabled }: {
  offer: TradeOffer; config: DraftConfig; teamNames?: Record<string, string>
  roster: TradeContextPlayer[]; week?: number
  cardRef: (node: HTMLElement | null) => void; isLinked: boolean; disabled: boolean
}) {
  const counterparty = (offer.to_team_id && teamNames?.[offer.to_team_id]) || `Team ${offer.to_team_id}`
  const evaluation = isProposalEvaluation(offer.evaluation) ? offer.evaluation : undefined
  // VORP and byes for the week the pitch was scored on, not whichever week the page shows.
  const scoredWeek = evaluation?.request.week ?? week
  const [message, setMessage] = useState(offer.message ?? '')
  const [editing, setEditing] = useState(false)
  return (
    <Card className="proposal-card" p="lg" withBorder radius="md" component="article"
      ref={cardRef}
      aria-current={isLinked || undefined}
      style={isLinked ? linkedOfferStyle : undefined}>
      <Group className="proposal-card-heading" justify="space-between" mb="sm">
        <Stack className="proposal-counterparty" gap={4}><Text size="xs" c="dimmed" tt="uppercase">Trade with</Text><Text size="lg" fw={700}>{counterparty}</Text>
        <Group gap={4}>
          <Badge color="yellow">Awaiting approval</Badge>
          {evaluation?.score.schedule.weeks.filter(week => week.head_to_head).map(week => <Badge key={week.week} color="blue" variant="light">Head-to-head wk {week.week}</Badge>)}
          {evaluation?.score.bye_coverage?.us.fixed.map(week => <Badge key={week} color="teal" variant="light">Covers your wk {week} crunch</Badge>)}
        </Group></Stack>
        <ProposalVerdict offer={offer} />
      </Group>
      <SimpleGrid cols={{ base: 1, sm: 2 }}>
        <ProposalPlayers label="You get" players={offer.incoming_players} roster={roster} week={scoredWeek} />
        <ProposalPlayers label="You give" players={offer.outgoing_players} roster={roster} week={scoredWeek} />
      </SimpleGrid>
      <ProposalScoreSummary compact offer={offer} teamNames={teamNames} />
      <Text size="xs" c="dimmed" mt="sm">
        Generated <time dateTime={offer.executed_at}>{new Date(offer.executed_at).toLocaleString()}</time>
      </Text>
      <ProposalMessage readOnly={offer.message_edited} editedBy={offer.edited_by} value={message} draft={offer.drafted_message ?? offer.message ?? ''} counterparty={counterparty} onChange={setMessage} onEditingChange={setEditing} />
      <TradeOfferApproval key={`${config.league_id}:${config.team_id}:${config.season}:${config.mode}:${offer.offer_key || offer.id}`}
        config={config} offer={offer} finalMessage={message} counterparty={counterparty}
        disabled={disabled || editing} />
    </Card>
  )
}
